import { useCallback, useState } from 'react';
import {
  View, Text, StyleSheet, ScrollView, Pressable, ActivityIndicator,
  Image, Modal, Alert, Share,
} from 'react-native';
import { useFocusEffect } from 'expo-router';
import { useTheme, spacing, radius, typography } from '../src/theme';
import { supabase } from '../src/api/supabase';
import { useAuth } from '../src/store/auth';
import { markScanOutcome, deleteScan } from '../src/utils/scanLog';
import { shareScanReport } from '../src/utils/scanReport';

const FILTERS = ['ALL', 'CROPS', 'PESTS', 'SOIL', 'LIVESTOCK', 'VIDEO'];

const TYPE_LABEL: Record<string, string> = {
  crops: 'Crop disease',
  pests: 'Pest',
  soil: 'Soil',
  livestock: 'Livestock',
  video: 'Video scan',
};

const TYPE_EMOJI: Record<string, string> = {
  crops: 'C', pests: 'P', soil: 'S', livestock: 'L', video: 'V',
};

function dayLabel(iso: string): string {
  const d = new Date(iso);
  const now = new Date();
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const scanDay = new Date(d.getFullYear(), d.getMonth(), d.getDate());
  const diff = Math.floor((today.getTime() - scanDay.getTime()) / 86400000);
  if (diff === 0) return 'Today';
  if (diff === 1) return 'Yesterday';
  if (diff < 7) return 'This week';
  if (diff < 30) return 'This month';
  return d.toLocaleDateString('en-NG', { month: 'long', year: 'numeric' });
}

export default function History() {
  const { palette } = useTheme();
  const { user } = useAuth();
  const styles = createStyles(palette);
  const [scans, setScans] = useState<any[]>([]);
  const [filter, setFilter] = useState('ALL');
  const [busy, setBusy] = useState(true);
  const [selected, setSelected] = useState<any | null>(null);
  const [followUps, setFollowUps] = useState<Record<string, any[]>>({});

  const load = useCallback(async () => {
    if (!user) return;
    setBusy(true);
    try {
      const { data } = await supabase
        .from('scan_history')
        .select('*')
        .eq('user_id', user.id)
        .order('created_at', { ascending: false })
        .limit(500);
      setScans(data || []);
      const chains: Record<string, any[]> = {};
      (data || []).forEach((s: any) => {
        if (s.follow_up_of) {
          if (!chains[s.follow_up_of]) chains[s.follow_up_of] = [];
          chains[s.follow_up_of].push(s);
        }
      });
      setFollowUps(chains);
    } catch (e) {
      console.warn('history load failed', e);
    } finally {
      setBusy(false);
    }
  }, [user]);

  useFocusEffect(useCallback(() => { load(); }, [load]));

  const filtered = filter === 'ALL'
    ? scans.filter((s) => !s.follow_up_of)
    : scans.filter((s) => !s.follow_up_of && (s.type || '').toUpperCase() === filter);

  const grouped: Record<string, any[]> = {};
  filtered.forEach((s) => {
    const label = dayLabel(s.created_at);
    if (!grouped[label]) grouped[label] = [];
    grouped[label].push(s);
  });

  const shareScan = async (s: any) => {
    try {
      const summary =
        'GAIA Scan Report\n\n' +
        'Type: ' + (TYPE_LABEL[s.type] || s.type) + '\n' +
        'Result: ' + (s.top_label || 'Unknown') + '\n' +
        'Confidence: ' + Math.round(s.confidence || 0) + '%\n' +
        'Date: ' + new Date(s.created_at).toLocaleString() + '\n' +
        (s.image_url ? 'Photo: ' + s.image_url + '\n' : '') +
        '\nGenerated by GAIA';
      await Share.share({ message: summary });
    } catch (e) {
      Alert.alert('Share failed', String(e));
    }
  };

  const handleOutcome = async (scanId: string, outcome: 'improved' | 'worsened' | 'resolved') => {
    const ok = await markScanOutcome(scanId, outcome);
    if (ok) {
      Alert.alert('Saved', 'Outcome recorded');
      setSelected(null);
      load();
    } else {
      Alert.alert('Failed', 'Try again');
    }
  };

  const handleDelete = (scanId: string) => {
    Alert.alert('Delete this scan?', 'This cannot be undone.', [
      { text: 'Cancel', style: 'cancel' },
      { text: 'Delete', style: 'destructive', onPress: async () => {
        const ok = await deleteScan(scanId);
        if (ok) { setSelected(null); load(); }
        else Alert.alert('Failed', 'Try again');
      }},
    ]);
  };

  const totalScans = scans.length;
  const treatedCount = Object.keys(followUps).length;

  return (
    <View style={styles.container}>
      <ScrollView contentContainerStyle={styles.scroll}>
        <Text style={styles.title}>Scan History</Text>
        <Text style={styles.subtitle}>
          {totalScans} scan{totalScans === 1 ? '' : 's'} · {treatedCount} treated
        </Text>

        <ScrollView horizontal showsHorizontalScrollIndicator={false} style={{ marginTop: 16, marginBottom: 8 }}>
          <View style={{ flexDirection: 'row', gap: 8, paddingRight: 20 }}>
            {FILTERS.map((f) => (
              <Pressable
                key={f}
                onPress={() => setFilter(f)}
                style={[styles.chip, filter === f && styles.chipActive]}
              >
                <Text style={[styles.chipText, filter === f && styles.chipTextActive]}>{f}</Text>
              </Pressable>
            ))}
          </View>
        </ScrollView>

        {busy ? <ActivityIndicator color={palette.neon} style={{ marginTop: 20 }} /> : null}

        {!busy && filtered.length === 0 ? (
          <View style={styles.emptyWrap}>
            <Text style={styles.emptyIcon}>C</Text>
            <Text style={styles.emptyTitle}>No scans yet</Text>
            <Text style={styles.emptyText}>
              Diagnose a crop, pest, soil sample, or animal to start building your farm history.
            </Text>
          </View>
        ) : null}

        {Object.entries(grouped).map(([day, items]) => (
          <View key={day} style={{ marginTop: 20 }}>
            <Text style={styles.dayLabel}>{day.toUpperCase()}</Text>
            {items.map((s) => {
              const chain = followUps[s.id] || [];
              const hasChain = chain.length > 0;
              return (
                <Pressable key={s.id} onPress={() => setSelected(s)} style={styles.card}>
                  <View style={styles.row}>
                    {s.image_url ? (
                      <Image source={{ uri: s.image_url }} style={styles.thumb} />
                    ) : (
                      <View style={[styles.thumb, styles.thumbFallback]}>
                        <Text style={styles.thumbFallbackText}>{TYPE_EMOJI[s.type] || '?'}</Text>
                      </View>
                    )}
                    <View style={{ flex: 1 }}>
                      <Text style={styles.itemTitle} numberOfLines={1}>{s.top_label || 'Unknown'}</Text>
                      <Text style={styles.itemSub}>
                        {TYPE_LABEL[s.type] || s.type} · {new Date(s.created_at).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                      </Text>
                      <View style={{ flexDirection: 'row', gap: 4, marginTop: 4, flexWrap: 'wrap' }}>
                        {s.on_device ? (
                          <Text style={[styles.badge, styles.badgeOnDevice]}>On-device</Text>
                        ) : (
                          <Text style={[styles.badge, styles.badgeServer]}>Server</Text>
                        )}
                        {hasChain ? (
                          <Text style={[styles.badge, styles.badgeFollowUp]}>
                            {chain.length} follow-up
                          </Text>
                        ) : null}
                        {s.outcome ? (
                          <Text style={[styles.badge, s.outcome === 'improved' || s.outcome === 'resolved' ? styles.badgeGood : styles.badgeBad]}>
                            {s.outcome === 'improved' ? 'Improved' : s.outcome === 'resolved' ? 'Resolved' : 'Worsened'}
                          </Text>
                        ) : null}
                      </View>
                    </View>
                    <Text style={styles.score}>{Math.round(s.confidence || 0)}%</Text>
                  </View>
                </Pressable>
              );
            })}
          </View>
        ))}

        <View style={{ height: 120 }} />
      </ScrollView>

      <Modal visible={!!selected} animationType="slide" transparent onRequestClose={() => setSelected(null)}>
        <View style={styles.modalBg}>
          <View style={styles.modalSheet}>
            <ScrollView>
              <Pressable onPress={() => setSelected(null)}>
                <Text style={styles.back}>CLOSE</Text>
              </Pressable>

              {selected ? (
                <>
                  <Text style={styles.modalTitle}>{selected.top_label}</Text>
                  <Text style={styles.modalSub}>
                    {TYPE_LABEL[selected.type] || selected.type} · {Math.round(selected.confidence || 0)}% confidence
                  </Text>
                  <Text style={styles.modalMeta}>{new Date(selected.created_at).toLocaleString()}</Text>

                  {selected.image_url ? (
                    <Image source={{ uri: selected.image_url }} style={styles.modalImage} resizeMode="contain" />
                  ) : null}

                  <Text style={styles.sectionLabel}>PREDICTIONS</Text>
                  {(selected.all_predictions || []).slice(0, 5).map((p: any, i: number) => (
                    <View key={i} style={styles.predRow}>
                      <Text style={styles.predLabel} numberOfLines={1}>{p.label}</Text>
                      <View style={styles.predBar}>
                        <View style={[styles.predFill, { width: Math.min(100, p.confidence) + '%' }]} />
                      </View>
                      <Text style={styles.predVal}>{Math.round(p.confidence)}%</Text>
                    </View>
                  ))}

                  {(followUps[selected.id] || []).length > 0 ? (
                    <>
                      <Text style={styles.sectionLabel}>FOLLOW-UP SCANS</Text>
                      {(followUps[selected.id] || []).map((f: any) => (
                        <View key={f.id} style={styles.chainCard}>
                          <Text style={styles.chainDate}>{new Date(f.created_at).toLocaleDateString()}</Text>
                          <Text style={styles.chainLabel}>{f.top_label} · {Math.round(f.confidence)}%</Text>
                          {f.outcome ? <Text style={styles.chainOutcome}>Outcome: {f.outcome}</Text> : null}
                        </View>
                      ))}
                    </>
                  ) : (
                    <>
                      <Text style={styles.sectionLabel}>HOW DID IT GO?</Text>
                      <View style={{ flexDirection: 'row', gap: 8, flexWrap: 'wrap' }}>
                        <Pressable onPress={() => handleOutcome(selected.id, 'improved')} style={[styles.outcomeBtn, { borderColor: '#00ff88' }]}>
                          <Text style={[styles.outcomeText, { color: '#00ff88' }]}>Improved</Text>
                        </Pressable>
                        <Pressable onPress={() => handleOutcome(selected.id, 'worsened')} style={[styles.outcomeBtn, { borderColor: '#ff3b5c' }]}>
                          <Text style={[styles.outcomeText, { color: '#ff3b5c' }]}>Worsened</Text>
                        </Pressable>
                        <Pressable onPress={() => handleOutcome(selected.id, 'resolved')} style={[styles.outcomeBtn, { borderColor: '#4fc3f7' }]}>
                          <Text style={[styles.outcomeText, { color: '#4fc3f7' }]}>Resolved</Text>
                        </Pressable>
                      </View>
                    </>
                  )}

                  <Text style={styles.sectionLabel}>EXPORT</Text>
                  <Pressable onPress={async () => {
                    Alert.alert('Export report', 'Generate a PDF farm health report?', [
                      { text: 'Cancel', style: 'cancel' },
                      { text: 'Generate', onPress: async () => {
                        const r = await shareScanReport({ days: 90 });
                        if (!r.ok) Alert.alert('Failed', r.error || 'Try again');
                      }},
                    ]);
                  }} style={styles.shareBtn}>
                    <Text style={styles.shareText}>PDF Farm Report (90 days)</Text>
                  </Pressable>

                  <Pressable onPress={() => shareScan(selected)} style={[styles.shareBtn, { marginTop: 10, backgroundColor: palette.surface, borderWidth: 1.5, borderColor: palette.neon }]}>
                    <Text style={[styles.shareText, { color: palette.neon }]}>Share this scan</Text>
                  </Pressable>

                  <Pressable onPress={() => handleDelete(selected.id)} style={[styles.shareBtn, { backgroundColor: 'transparent', borderWidth: 1.5, borderColor: '#ff3b5c', marginTop: 10 }]}>
                    <Text style={[styles.shareText, { color: '#ff3b5c' }]}>Delete scan</Text>
                  </Pressable>

                  <View style={{ height: 60 }} />
                </>
              ) : null}
            </ScrollView>
          </View>
        </View>
      </Modal>
    </View>
  );
}

